import 'dart:convert';

import '../core/event_models.dart';
import '../core/serializer.dart';

// ---------------------------------------------------------------------------
// FlightSynthesizer
// ---------------------------------------------------------------------------

/// Generates valid, executable Dart `testWidgets` code from a [FlightSession].
///
/// ## Upgraded capabilities (v2)
///
/// * **Semantic pointer events** – [SemanticPointerFlightEvent] instances are
///   turned into `tester.tap(find.byKey(...))` / `tester.tap(find.text(...))`
///   etc., rather than raw `tester.tapAt(Offset(...))` calls.
/// * **Scroll events** – pointer events with `action == 'scroll'` are
///   synthesised as `tester.drag(finder, Offset(ddx, ddy))`.
/// * **Text-input events** – [TextInputFlightEvent] is turned into
///   `tester.enterText(finder, text)`.
/// * **Platform-channel stubs** – [PlatformChannelFlightEvent] instances
///   generate `setMockMethodCallHandler` stubs at the top of the test.
/// * **WebSocket fixtures** – [WebSocketFlightEvent] instances generate a
///   `FlightWebSocketReplayServer` fixture block.
/// * **Route stack context** – the first [RouteStackSnapshotEvent] found in
///   the session generates a deep-route comment block.
/// * **DI bootstrap comment** – every generated test includes a DI comment
///   block reminding the developer to wire up their DI framework.
class FlightSynthesizer {
  /// Generates the complete Dart test file string.
  static String synthesize({
    required FlightSession session,
    String testDescription = 'Reproduced Flight Recorder Session',
    String appWidgetConstructor =
        'const Placeholder() /* Replace with your app root widget e.g. MyApp() */',
  }) {
    final buffer = StringBuffer();
    final manifest = session.manifest;
    final events = session.events;

    // ------------------------------------------------------------------
    // 1. Header comments
    // ------------------------------------------------------------------
    buffer.writeln('// -------------------------------------------------------------');
    buffer.writeln('// AUTO-GENERATED BY FLIGHT RECORDER');
    buffer.writeln('// Session ID: ${manifest.sessionId}');
    buffer.writeln('// Recorded: ${manifest.startedAt.toIso8601String()}');
    buffer.writeln('// Platform: ${manifest.platform}');
    buffer.writeln('// Total Events: ${events.length}');
    buffer.writeln('// -------------------------------------------------------------\n');

    // ------------------------------------------------------------------
    // 2. Imports
    // ------------------------------------------------------------------
    buffer.writeln("import 'package:flutter/material.dart';");
    buffer.writeln("import 'package:flutter_test/flutter_test.dart';");
    buffer.writeln("import 'package:flight_recorder/flight_recorder.dart';");
    buffer.writeln();

    // ------------------------------------------------------------------
    // 3. HTTP Fixtures extraction
    // ------------------------------------------------------------------
    final httpEvents = events.whereType<HttpFlightEvent>().toList();
    if (httpEvents.isNotEmpty) {
      buffer.writeln('/// Captured HTTP Fixtures from the flight session');
      buffer.writeln('final List<ReplayFixture> _recordedFixtures = [');
      for (final http in httpEvents) {
        final bodyEscaped = _escapeDartRawString(http.responseBody ?? '');
        buffer.writeln('  ReplayFixture(');
        buffer.writeln("    method: '${http.method}',");
        buffer.writeln("    urlPattern: '${_escapeString(http.url)}',");
        buffer.writeln('    statusCode: ${http.statusCode},');
        buffer.writeln('    responseBody: $bodyEscaped,');
        buffer.writeln('  ),');
      }
      buffer.writeln('];\n');
    }

    // ------------------------------------------------------------------
    // 4. WebSocket fixtures
    // ------------------------------------------------------------------
    final wsEvents = events.whereType<WebSocketFlightEvent>().toList();
    if (wsEvents.isNotEmpty) {
      buffer.writeln('/// Captured WebSocket fixtures from the flight session.');
      buffer.writeln(
          '/// Feed these into FlightWebSocketReplayServer to replay WS traffic.');
      buffer.writeln('final List<WebSocketFixture> _recordedWebSocketFixtures = [');
      for (final ws in wsEvents) {
        final payloadEscaped = _escapeDartRawString(ws.payload ?? '');
        buffer.writeln('  WebSocketFixture(');
        buffer.writeln("    url: '${_escapeString(ws.url)}',");
        buffer.writeln("    direction: '${ws.direction}',");
        buffer.writeln('    payload: $payloadEscaped,');
        buffer.writeln('    timestampMs: ${ws.timestampMs},');
        buffer.writeln('  ),');
      }
      buffer.writeln('];\n');
    }

    // ------------------------------------------------------------------
    // 5. Test function
    // ------------------------------------------------------------------
    buffer.writeln('void main() {');
    buffer.writeln("  testWidgets('$testDescription', (WidgetTester tester) async {");

    // ------------------------------------------------------------------
    // 5a. Viewport setup
    // ------------------------------------------------------------------
    final physicalWidth =
        (manifest.initialWidth * manifest.initialDevicePixelRatio)
            .toStringAsFixed(1);
    final physicalHeight =
        (manifest.initialHeight * manifest.initialDevicePixelRatio)
            .toStringAsFixed(1);
    final dpr = manifest.initialDevicePixelRatio.toStringAsFixed(2);

    buffer.writeln(
        '    // 1. Configure viewport & device metrics to match recording');
    buffer.writeln(
        '    tester.view.physicalSize = const Size($physicalWidth, $physicalHeight);');
    buffer.writeln('    tester.view.devicePixelRatio = $dpr;');
    buffer.writeln('    addTearDown(tester.view.resetPhysicalSize);');
    buffer.writeln('    addTearDown(tester.view.resetDevicePixelRatio);');
    buffer.writeln();

    // ------------------------------------------------------------------
    // 5b. Route context comment (from first RouteStackSnapshotEvent)
    // ------------------------------------------------------------------
    final routeSnapshot =
        events.whereType<RouteStackSnapshotEvent>().firstOrNull;
    if (routeSnapshot != null && routeSnapshot.stack.isNotEmpty) {
      final stackRepr =
          routeSnapshot.stack.map((r) => "'$r'").join(', ');
      final deepest = routeSnapshot.stack.last;
      buffer.writeln('    // 2. Route Context');
      buffer.writeln(
          '    // DEEP ROUTE CONTEXT (recorded from: [$stackRepr])');
      buffer.writeln(
          '    // Your test harness MUST navigate to: $deepest');
      buffer.writeln(
          '    // Suggested approach: inject an initialRoute or use a GoRouter override.');
      buffer.writeln();
    }

    // ------------------------------------------------------------------
    // 5c. Platform-channel stubs
    // ------------------------------------------------------------------
    final channelEvents =
        events.whereType<PlatformChannelFlightEvent>().toList();
    // Deduplicate by channel name so we emit one stub per channel.
    final seenChannels = <String>{};
    final uniqueChannelEvents =
        channelEvents.where((e) => seenChannels.add(e.channelName)).toList();

    if (uniqueChannelEvents.isNotEmpty) {
      buffer.writeln('    // Platform channel stubs');
      for (final ch in uniqueChannelEvents) {
        final resultLiteral = ch.resultJson != null
            ? _escapeDartRawString(ch.resultJson!)
            : "'\\'[REDACTED]\\''";
        buffer.writeln(
            '    tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(');
        buffer.writeln(
            "      const MethodChannel('${_escapeString(ch.channelName)}'),");
        buffer.writeln('      (call) async { return $resultLiteral; },');
        buffer.writeln('    );');
      }
      buffer.writeln();
    }

    // ------------------------------------------------------------------
    // 5d. WebSocket replay server setup
    // ------------------------------------------------------------------
    if (wsEvents.isNotEmpty) {
      buffer.writeln('    // WebSocket replay server');
      buffer.writeln(
          '    final wsReplayServer = FlightWebSocketReplayServer(fixtures: _recordedWebSocketFixtures);');
      buffer.writeln('    wsReplayServer.install();');
      buffer.writeln('    addTearDown(wsReplayServer.uninstall);');
      buffer.writeln();
    }

    // ------------------------------------------------------------------
    // 5e. HTTP replay server setup
    // ------------------------------------------------------------------
    if (httpEvents.isNotEmpty) {
      buffer.writeln(
          '    // ${routeSnapshot != null ? '3' : '2'}. Install deterministic HTTP replay server');
      buffer.writeln(
          '    final replayServer = FlightReplayServer(fixtures: _recordedFixtures);');
      buffer.writeln('    replayServer.install();');
      buffer.writeln('    addTearDown(replayServer.uninstall);');
      buffer.writeln();
    }

    // ------------------------------------------------------------------
    // 5f. DI bootstrap comment
    // ------------------------------------------------------------------
    buffer.writeln(
        "    // \u26a0\ufe0f DI BOOTSTRAP: Replace 'const MyApp()' with your test-bootstrapped app.");
    buffer.writeln('    // Example for Riverpod:');
    buffer.writeln(
        '    //   await tester.pumpWidget(ProviderScope(overrides: [...], child: const MyApp()));');
    buffer.writeln('    // Example for GetIt:');
    buffer.writeln('    //   setupTestDependencies();');
    buffer.writeln('    //   await tester.pumpWidget(const MyApp());');
    buffer.writeln();

    // ------------------------------------------------------------------
    // 5g. Pump root widget
    // ------------------------------------------------------------------
    final httpOrWs = httpEvents.isNotEmpty || wsEvents.isNotEmpty;
    final pumpSectionNum =
        (routeSnapshot != null ? 2 : 1) + (httpOrWs ? 1 : 0) + 1;
    buffer.writeln('    // $pumpSectionNum. Pump application tree');
    buffer.writeln('    await tester.pumpWidget($appWidgetConstructor);');
    buffer.writeln('    await tester.pumpAndSettle();');
    buffer.writeln();

    // ------------------------------------------------------------------
    // 5h. Deterministic interaction replay
    // ------------------------------------------------------------------
    buffer.writeln('    // ${pumpSectionNum + 1}. Deterministic interaction replay');

    int lastTimestampMs = 0;
    for (int i = 0; i < events.length; i++) {
      final event = events[i];
      final delta = event.timestampMs - lastTimestampMs;

      if (delta > 0) {
        buffer.writeln(
            '    await tester.pump(const Duration(milliseconds: $delta));');
        lastTimestampMs = event.timestampMs;
      }

      // ----------------------------------------------------------------
      // SemanticPointerFlightEvent – preferred semantic-finder path
      // ----------------------------------------------------------------
      if (event is SemanticPointerFlightEvent) {
        _synthesizeSemanticPointerEvent(
          buffer,
          event,
          events,
          i,
          (newI) {
            i = newI;
            lastTimestampMs = events[newI].timestampMs;
          },
        );
        continue;
      }

      // ----------------------------------------------------------------
      // PointerFlightEvent – existing logic + scroll handling
      // ----------------------------------------------------------------
      if (event is PointerFlightEvent) {
        // Scroll events → tester.drag
        if (event.action == 'scroll') {
          _synthesizeScrollEvent(buffer, event);
          continue;
        }

        // Check if this is a clean tap: down followed quickly by up at a
        // similar position.
        if (event.action == 'down' && i + 1 < events.length) {
          final next = events[i + 1];
          if (next is PointerFlightEvent &&
              next.action == 'up' &&
              (next.dx - event.dx).abs() < 5 &&
              (next.dy - event.dy).abs() < 5) {
            final tapDelta = next.timestampMs - event.timestampMs;
            buffer.writeln(
                '    // Tap at (${event.dx.toStringAsFixed(1)}, ${event.dy.toStringAsFixed(1)})');
            buffer.writeln(
                '    await tester.tapAt(const Offset(${event.dx.toStringAsFixed(1)}, ${event.dy.toStringAsFixed(1)}));');
            if (tapDelta > 0) {
              buffer.writeln(
                  '    await tester.pump(const Duration(milliseconds: $tapDelta));');
            }
            lastTimestampMs = next.timestampMs;
            i++; // Skip the up event
            continue;
          }
        }

        buffer.writeln(
          '    await FlightPointerInjector.inject(tester, PointerFlightEvent('
          'timestampMs: ${event.timestampMs}, '
          "action: '${event.action}', "
          'dx: ${event.dx.toStringAsFixed(1)}, '
          'dy: ${event.dy.toStringAsFixed(1)}, '
          'pointerId: ${event.pointerId}, '
          'buttons: ${event.buttons}, '
          "deviceKind: '${event.deviceKind}', "
          'scrollDeltaDx: ${event.scrollDeltaDx.toStringAsFixed(1)}, '
          'scrollDeltaDy: ${event.scrollDeltaDy.toStringAsFixed(1)},'
          '));',
        );
        continue;
      }

      // ----------------------------------------------------------------
      // TextInputFlightEvent
      // ----------------------------------------------------------------
      if (event is TextInputFlightEvent) {
        _synthesizeTextInputEvent(buffer, event);
        continue;
      }

      // ----------------------------------------------------------------
      // PlatformChannelFlightEvent – already handled as stubs above;
      // emit a comment at the interaction point for context.
      // ----------------------------------------------------------------
      if (event is PlatformChannelFlightEvent) {
        buffer.writeln(
            "    // [PlatformChannel] '${event.channelName}' \u2192 '${event.methodName ?? '(unknown)'}'");
        continue;
      }

      // ----------------------------------------------------------------
      // WebSocketFlightEvent – emit comment at interaction point.
      // ----------------------------------------------------------------
      if (event is WebSocketFlightEvent) {
        buffer.writeln(
            '    // [WebSocket/${event.direction}] ${event.url}');
        continue;
      }

      // ----------------------------------------------------------------
      // RouteStackSnapshotEvent – rendered at top; emit comment here too.
      // ----------------------------------------------------------------
      if (event is RouteStackSnapshotEvent) {
        final stackRepr =
            event.stack.map((r) => "'$r'").join(', ');
        buffer.writeln(
            '    // [RouteStack snapshot] [$stackRepr]');
        continue;
      }

      // ----------------------------------------------------------------
      // NavigationFlightEvent
      // ----------------------------------------------------------------
      if (event is NavigationFlightEvent) {
        buffer.writeln(
            "    // [Route] ${event.action} -> '${event.routeName}'");
        continue;
      }

      // ----------------------------------------------------------------
      // CustomBreadcrumbFlightEvent
      // ----------------------------------------------------------------
      if (event is CustomBreadcrumbFlightEvent) {
        buffer.writeln(
            "    // [Breadcrumb] '${event.name}' (${event.category})");
        continue;
      }

      // ----------------------------------------------------------------
      // CrashFlightEvent
      // ----------------------------------------------------------------
      if (event is CrashFlightEvent) {
        buffer.writeln(
            '    // ---------------------------------------------------------');
        buffer.writeln('    // CRASH OCCURRED AT THIS STEP:');
        buffer.writeln(
            '    // Exception: ${_escapeString(event.exception)}');
        buffer.writeln(
            '    // ---------------------------------------------------------');
        buffer.writeln('    await tester.pump();');
        continue;
      }
    }

    buffer.writeln('  });');
    buffer.writeln('}\n');

    return buffer.toString();
  }

  // -------------------------------------------------------------------------
  // Semantic pointer synthesis
  // -------------------------------------------------------------------------

  /// Synthesises a [SemanticPointerFlightEvent] into a `tester.tap(finder)`
  /// or `tester.drag(finder, delta)` call.
  ///
  /// [onAdvance] is called when the loop index needs to be advanced (e.g. to
  /// swallow a matching 'up' event that follows a 'down').
  static void _synthesizeSemanticPointerEvent(
    StringBuffer buffer,
    SemanticPointerFlightEvent event,
    List<FlightEvent> events,
    int i,
    void Function(int newI) onAdvance,
  ) {
    // Scroll events are handled by delta regardless of semantic identity.
    if (event.action == 'scroll') {
      _synthesizeScrollEvent(buffer, event);
      return;
    }

    // For a down event that is semantically resolved, look ahead for the
    // matching up event.
    if (event.action == 'down' && event.hasSemantic && i + 1 < events.length) {
      final next = events[i + 1];
      if (next is PointerFlightEvent &&
          next.action == 'up' &&
          (next.dx - event.dx).abs() < 5 &&
          (next.dy - event.dy).abs() < 5) {
        final finder = event.toFinderExpression();
        buffer.writeln('    // Tap: ${_identitySummary(event)}');
        buffer.writeln('    await tester.tap($finder);');
        final tapDelta = next.timestampMs - event.timestampMs;
        if (tapDelta > 0) {
          buffer.writeln(
              '    await tester.pump(const Duration(milliseconds: $tapDelta));');
        }
        onAdvance(i + 1);
        return;
      }
    }

    // A fully-resolved 'tap' action (single atomic event already representing
    // a complete tap gesture).
    if (event.action == 'tap' && event.hasSemantic) {
      final finder = event.toFinderExpression();
      buffer.writeln('    // Tap: ${_identitySummary(event)}');
      buffer.writeln('    await tester.tap($finder);');
      return;
    }

    // Long press.
    if (event.action == 'longPress' && event.hasSemantic) {
      final finder = event.toFinderExpression();
      buffer.writeln('    // Long press: ${_identitySummary(event)}');
      buffer.writeln('    await tester.longPress($finder);');
      return;
    }

    // Fallback: use raw tapAt when no semantic info available or action doesn't
    // match the patterns above.
    if (event.action == 'down' && i + 1 < events.length) {
      final next = events[i + 1];
      if (next is PointerFlightEvent &&
          next.action == 'up' &&
          (next.dx - event.dx).abs() < 5 &&
          (next.dy - event.dy).abs() < 5) {
        buffer.writeln(
            '    // Tap at (${event.dx.toStringAsFixed(1)}, ${event.dy.toStringAsFixed(1)})');
        buffer.writeln(
            '    await tester.tapAt(const Offset(${event.dx.toStringAsFixed(1)}, ${event.dy.toStringAsFixed(1)}));');
        final tapDelta = next.timestampMs - event.timestampMs;
        if (tapDelta > 0) {
          buffer.writeln(
              '    await tester.pump(const Duration(milliseconds: $tapDelta));');
        }
        onAdvance(i + 1);
        return;
      }
    }

    // Generic injection fallback.
    buffer.writeln(
      '    await FlightPointerInjector.inject(tester, PointerFlightEvent('
      'timestampMs: ${event.timestampMs}, '
      "action: '${event.action}', "
      'dx: ${event.dx.toStringAsFixed(1)}, '
      'dy: ${event.dy.toStringAsFixed(1)}, '
      'pointerId: ${event.pointerId}, '
      'buttons: ${event.buttons}, '
      "deviceKind: '${event.deviceKind}', "
      'scrollDeltaDx: ${event.scrollDeltaDx.toStringAsFixed(1)}, '
      'scrollDeltaDy: ${event.scrollDeltaDy.toStringAsFixed(1)},'
      '));',
    );
  }

  // -------------------------------------------------------------------------
  // Scroll synthesis
  // -------------------------------------------------------------------------

  static void _synthesizeScrollEvent(
      StringBuffer buffer, PointerFlightEvent event) {
    final ddx = event.scrollDeltaDx.toStringAsFixed(1);
    final ddy = event.scrollDeltaDy.toStringAsFixed(1);
    // We attempt a drag on the widget at the scroll position. Since we may not
    // know the finder, we emit a hitTestable drag at the given offset.
    buffer.writeln(
        '    // Scroll at (${event.dx.toStringAsFixed(1)}, ${event.dy.toStringAsFixed(1)}) delta=($ddx, $ddy)');
    buffer.writeln(
        '    await tester.drag(find.hitTestable().at(const Offset(${event.dx.toStringAsFixed(1)}, ${event.dy.toStringAsFixed(1)})), const Offset($ddx, $ddy));');
    buffer.writeln('    await tester.pumpAndSettle();');
  }

  // -------------------------------------------------------------------------
  // Text-input synthesis
  // -------------------------------------------------------------------------

  static void _synthesizeTextInputEvent(
      StringBuffer buffer, TextInputFlightEvent event) {
    final String finder;
    if (event.fieldKey != null) {
      final escapedKey = _escapeString(event.fieldKey!);
      finder = "find.byKey(const Key('$escapedKey'))";
    } else if (event.fieldWidgetType != null) {
      finder = 'find.byType(${event.fieldWidgetType})';
    } else {
      finder = 'find.byType(TextField)';
    }
    final escapedText = _escapeDartRawString(event.text);
    buffer.writeln(
        '    // Enter text into ${event.fieldKey ?? event.fieldWidgetType ?? 'TextField'}');
    buffer.writeln('    await tester.enterText($finder, $escapedText);');
    buffer.writeln('    await tester.pumpAndSettle();');
  }

  // -------------------------------------------------------------------------
  // Helpers
  // -------------------------------------------------------------------------

  static String _identitySummary(SemanticPointerFlightEvent e) {
    if (e.resolvedKey != null) return "key='${e.resolvedKey}'";
    if (e.resolvedText != null) return "text='${e.resolvedText}'";
    if (e.resolvedTooltip != null) return "tooltip='${e.resolvedTooltip}'";
    if (e.resolvedSemLabel != null) return "semLabel='${e.resolvedSemLabel}'";
    return 'type=${e.resolvedWidgetType ?? '?'}';
  }

  static String _escapeString(String str) {
    return str.replaceAll("'", r"\'").replaceAll('\n', r'\n');
  }

  static String _escapeDartRawString(String str) {
    if (str.isEmpty) return "''";
    // If it contains triple quotes, use normal JSON string encoding.
    if (str.contains("'''")) {
      return jsonEncode(str);
    }
    return "r'''$str'''";
  }
}
