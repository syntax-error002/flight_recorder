  static int _findMatchingUpIndex(
    List<FlightEvent> events,
    int downIndex,
    PointerFlightEvent downEvent,
  ) {
    int pointerEventsSeen = 0;
    for (int k = downIndex + 1;
        k < events.length && k <= downIndex + 100;
        k++) {
      final ev = events[k];
      if (ev is PointerFlightEvent) {
        pointerEventsSeen++;
        if (pointerEventsSeen > 20) return -1;
        if (ev.action == 'down') {
          return -1;
        }
        if (ev.action == 'move') {
          if ((ev.dx - downEvent.dx).abs() > 15 ||
              (ev.dy - downEvent.dy).abs() > 15) {
            return -1;
          }
        }
        if (ev.action == 'up') {
          if (ev.pointerId == downEvent.pointerId ||
              ((ev.dx - downEvent.dx).abs() < 15 &&
                  (ev.dy - downEvent.dy).abs() < 15)) {
            return k;
          }
        }
      }
    }
    return -1;
  }

  static String _identitySummary(SemanticPointerFlightEvent e) {
    if (e.resolvedKey != null) return "key='${e.resolvedKey}'";
    if (e.resolvedText != null) return "text='${e.resolvedText}'";
    if (e.resolvedTooltip != null) return "tooltip='${e.resolvedTooltip}'";
    if (e.resolvedSemLabel != null) return "semLabel='${e.resolvedSemLabel}'";
    return 'type=${e.resolvedWidgetType ?? '?'}';
  }

  static String _escapeString(String str) {
    return str.replaceAll("'", r"\'").replaceAll('\n', r'\n');
  }

  static String _escapeDartRawString(String str) {
    if (str.isEmpty) return "''";
    // If it contains triple quotes, use normal JSON string encoding.
    if (str.contains("'''")) {
      return jsonEncode(str);
    }
    return "r'''$str'''";
  }
